/*
Question:
Write a Java program to demonstrate the if statement.
Check whether a given number is greater than 10.

Concepts Covered:
- if statement
- int Data Type
- Variables
- Comparison Operator (>)
- System.out.println()

Sample Input:
15

Sample Output:
Number is greater than 10

Explanation:
The if statement is used to execute a block of code
when a given condition is true.


*/

public class IfStatementDemo {

    public static void main(String[] args) 
  {
     int num = 15;

        if (num > 10) 
        {
           System.out.println("Number is greater than 10");
     }
 }
}
